/**
 * Words that must pass through untouched.
 *
 * CODE_TOKENS is deliberately a whitelist (case-sensitive), NOT a shape rule:
 * an earlier version used `/^[\dA-Z]{0,3}$/i`, which silently swallowed every
 * short real word — "Oil", "Nut", "Kit" all survived untranslated. Whitelisting
 * keeps "EX"/"XP"/"RE" intact while letting "Oil" become "Öl".
 */
const CODE_TOKENS = /^(EX|XP|X|R|RE|LO|SPT|CR|VA|CE|NATO|ZB|LU|E\d+)$/;
const PASSTHROUGH = /^[\d.\-/]+$|^(mtu|weichai|cummins|deutz|doosan|volvo|perkins|yuchai|isuzu|scania|man|iveco|sdec|lovol|cat|caterpillar|nato|molykote|loctite|tripoly|seec|woodward|bosch|denso|delphi|parkner|parker|skf|fag|ina|schaeffler)$/i;

const phraseEntries = Object.entries(PHRASE_DE).sort((a, b) => b[0].length - a[0].length);

/** German words that are never capitalised mid-designation. */
const LOWERCASE_DE = new Set([
  'innen', 'außen', 'für', 'mit', 'mit Gewinde', 'hinten', 'vorn',
  'komplett', 'ummantelt', 'frei',
]);

/** Case-insensitive, boundary-safe pattern for one dictionary key. */
function keyPattern(en: string): RegExp {
  const body = en
    .replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
    .replace(/-/g, '\\s*-\\s*');
  // The lookarounds also reject a hyphen, so a short key like 'spin-on' can
  // never match inside an already-replaced 'Spin-on-Filter'.
  return new RegExp(`(?<![A-Za-z-])${body}(?![A-Za-z-])`, 'gi');
}

/** Translate one word, keeping an initial capital when the source had one. */
function translateWord(word: string): string {
  if (CODE_TOKENS.test(word) || PASSTHROUGH.test(word)) return word;
  const de = WORD_DE[word.toLowerCase()];
  if (!de) return word;
  // German adverbs, prepositions and participles are not capitalised, even
  // when the source word was ("Valve Spring Inner" → "Ventilfeder innen").
  if (LOWERCASE_DE.has(de)) return de;
  return /^[A-Z]/.test(word) ? de.charAt(0).toUpperCase() + de.slice(1) : de;
}

/**
 * German designation for a catalog part name.
 * Phrase matches win over word matches; unknown words stay English.
 */
export function germanPartName(name: string): string {
  if (!name || !name.trim()) return '';
  let out = ` ${name.trim()} `;

  // 1. Phrase-level (longest first), case-insensitive, word-boundary safe.
  for (const [en, de] of phraseEntries) {
    out = out.replace(keyPattern(en), () => ` ${de} `);
  }

  // 2. Word-level fallback. Hyphenated tokens are split so that
  // "Fuel-Injection" can become "Kraftstoff-Einspritzung"; if any part is
  // unknown the whole token is kept as-is rather than half-translated.
  out = out.replace(/[A-Za-z][A-Za-z-]*/g, (word) => {
    if (!word.includes('-')) return translateWord(word);
    const parts = word.split('-');
    if (parts.some((p) => !p || !WORD_DE[p.toLowerCase()])) return word;
    return parts.map(translateWord).join('-');
  });

  return out.replace(/\s+/g, ' ').trim();
}

