/**
 * German designations for catalog part names.
 *
 * Why this exists: MTU is a German brand and a large share of the engineers,
 * superintendents and purchasing desks that search for our parts work in
 * German (Germany, Austria, Switzerland, and much of the East European
 * fleet). The German designation is a standard column in every MTU parts
 * list, and competitors publish it — we did not, which meant German-language
 * part searches had no reason to land on our pages.
 *
 * How it works (and its limits):
 * - Multi-word compounds are matched first (longest phrase wins), so
 *   "Crankshaft Bearing" becomes "Kurbelwellenlager", not "Kurbelwelle Lager".
 * - Single words fall back to the word dictionary.
 * - Unknown words are kept in English. We do NOT guess: an invented German
 *   word is worse than an honest English one, and MTU group codes (LU, ZB,
 *   E531…) are not reproduced because we do not have the manufacturer's
 *   designation table.
 * - Numbers, hyphens, slashes and model codes pass through untouched.
 *
 * Every entry below is a standard technical term, not a creative translation.
 */

