import { copyFile, mkdir, readFile, writeFile } from 'node:fs/promises';
import { existsSync, readdirSync, rmSync, statSync } from 'node:fs';
import { join, resolve } from 'node:path';

const workerDir = resolve('dist/_worker.js');
const DIST = resolve('dist');
// Collected here (not at the bottom) so sections that run before the
// verification block can record a failure instead of only warning.
const failures = [];

const workerEntry = resolve(workerDir, 'index.js');
const workerSmtp = resolve(workerDir, 'zoho-smtp.js');
const workerRetired = resolve(workerDir, 'retired-paths.js');
const assetsIgnore = resolve('dist/.assetsignore');

const legacyMapSource = resolve('dist/seo-redirects.json'); // emitted by src/pages/seo-redirects.json.ts
const handWrittenSource = resolve('public/_redirects'); // the human-edited rule list
const retiredSource = resolve('src/data/retired-urls.txt'); // paths that must answer 410
const mergedRedirects = resolve('dist/_redirects'); // the single file Cloudflare reads

// Status codes Cloudflare's _redirects parser honours. Anything else (notably
// 410) is silently dropped by Cloudflare, so shipping one would leave the path
// falling back to a plain 404 — the exact failure mode we are fixing.
const CLOUDFLARE_STATUSES = new Set(['200', '301', '302', '303', '307', '308']);

// Files that must never be uploaded as static assets. `_worker.js` is source
// code; the rest is Astro's SSR build output, which a normal build deletes in
// `cleanServerOutput()` before the upload. That delete can be refused (sandbox
// guard), so every one of them is listed here explicitly rather than relying on
// it having happened — `manifest_*.mjs` is a glob because the name is hashed.
const ASSET_IGNORES = [
  '_worker.js',
  'pages',
  'chunks',
  'renderers.mjs',
  'noop-entrypoint.mjs',
  '_noop-middleware.mjs',
  'manifest_*.mjs',
  'seo-redirects.json',
];

/** Translate a .assetsignore (gitignore-style) pattern into a RegExp. */
function ignoreMatcher(pattern) {
  const escaped = pattern.replace(/[.+^${}()|[\]\\]/g, '\\$&').replace(/\*/g, '.*');
  return new RegExp(`^${escaped}$`);
}

await mkdir(workerDir, { recursive: true });

// ---------------------------------------------------------------------------
// 0. Retired paths -> ./retired-paths.js  (written BEFORE index.js is copied,
//    so the module index.js imports always exists)
// ---------------------------------------------------------------------------
// Cloudflare's _redirects supports 301/302/303/307/308 and 200 rewrites only.
// 410 Gone is not expressible there, so retired URLs are answered by the
// Worker instead. Source of truth: src/data/retired-urls.txt
// ---------------------------------------------------------------------------
let retiredPaths = [];
try {
  const text = await readFile(retiredSource, 'utf8');
  retiredPaths = [
    ...new Set(
      text
        .split(/\r?\n/)
        .map((line) => line.trim())
        .filter((line) => line.startsWith('/'))
        // stored without the trailing slash so one entry covers both
        // `/foo/` and `/foo`
        .map((path) => (path.replace(/\/+$/, '') || '/')),
    ),
  ];
} catch {
  console.warn(`! ${retiredSource} missing — the Worker will not answer any 410.`);
}

await writeFile(
  workerRetired,
  [
    '// GENERATED by scripts/create-worker-entry.mjs — do not edit by hand.',
    '//',
    '// Source of truth: src/data/retired-urls.txt',
    '// Why here: Cloudflare _redirects cannot express 410 Gone, so the Worker',
    '// answers these paths. Paths are stored WITHOUT a trailing slash; the',
    '// Worker normalises the request path before matching.',
    '',
    'export const RETIRED_PATHS = new Set([',
    ...retiredPaths.map((path) => `  ${JSON.stringify(path)},`),
    ']);',
    '',
  ].join('\n'),
  'utf8',
);

await copyFile(resolve('cloudflare-worker.js'), workerEntry);
await copyFile(resolve('zoho-smtp.js'), workerSmtp);

await writeFile(assetsIgnore, `${ASSET_IGNORES.join('\n')}\n`, 'utf8');

// ---------------------------------------------------------------------------
// Redirects
// ---------------------------------------------------------------------------
// All redirect rules are merged into a single dist/_redirects file so there is
// exactly one place to audit. Cloudflare Workers Static Assets evaluates this
// file for every request — whether or not the path matches a stored asset —
// which is why the Worker itself owns no redirect logic.
//
// Two rule sources:
//   1. public/_redirects    — hand-written rules (old marketing URLs)
//   2. seo-redirects.json   — part pages that lost the duplicate-part-number
//                             race; generated from mtuPartSlugRedirects
// ---------------------------------------------------------------------------

let legacyMap = {};
try {
  legacyMap = JSON.parse(await readFile(legacyMapSource, 'utf8'));
} catch {
  // Not a warning: this file carries the duplicate-part-number redirects. A
  // missing one used to fall through as `{}` and silently produced a
  // dist/_redirects 24 rules weaker than the previous build's.
  failures.push(
    'dist/seo-redirects.json is missing — the duplicate-part-number part-page redirects ' +
      'would be dropped from dist/_redirects. It is emitted by src/pages/seo-redirects.json.ts, ' +
      'so this means `astro build` did not run (or did not finish).',
  );
}

// Cloudflare evaluates _redirects top-down and uses the FIRST matching rule, so
// a duplicated source path would silently shadow every rule below it.
const seenSources = new Set();
const skippedDuplicates = [];
const unsupportedStatuses = [];

function addRule(rule) {
  const source = rule.split(' ')[0];
  if (seenSources.has(source)) {
    skippedDuplicates.push(source);
    return false;
  }
  seenSources.add(source);
  return true;
}

const handWritten = [];
try {
  const text = await readFile(handWrittenSource, 'utf8');
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim();
    if (!line || line.startsWith('#')) continue;
    const rule = line.replace(/\s+/g, ' ');
    const status = rule.split(' ')[2] ?? '302';
    if (!CLOUDFLARE_STATUSES.has(status)) {
      unsupportedStatuses.push(rule);
      continue;
    }
    if (addRule(rule)) handWritten.push(rule);
  }
} catch {
  console.warn('! public/_redirects missing — no hand-written rules merged.');
}

const legacyPartRules = [];
for (const from of Object.keys(legacyMap).sort()) {
  const to = legacyMap[from];
  const rule = `/part-products/${from}/ /part-products/${to}/ 301`;
  if (addRule(rule)) legacyPartRules.push(rule);
}

if (skippedDuplicates.length) {
  console.warn(`! ${skippedDuplicates.length} duplicate redirect source(s) ignored: ${skippedDuplicates.join(', ')}`);
}
if (unsupportedStatuses.length) {
  console.warn(
    `! ${unsupportedStatuses.length} rule(s) dropped — status not supported by Cloudflare _redirects ` +
      `(410 belongs in src/data/retired-urls.txt):\n  ${unsupportedStatuses.join('\n  ')}`,
  );
}

const header = [
  '# GENERATED by scripts/create-worker-entry.mjs — do not edit by hand.',
  '#',
  '# Sources of truth:',
  '#   public/_redirects                          (hand-written rules)',
  '#   src/data/mtu-parts.ts -> mtuPartSlugRedirects  (part-page dedup map,',
  '#     emitted by src/pages/seo-redirects.json.ts)',
  '#   src/data/retired-urls.txt                  (410 Gone, served by the',
  '#     Worker — Cloudflare _redirects cannot express 410)',
  '#',
  '# Cloudflare Workers Static Assets applies this file to every request,',
  '# static match or not. Rules are evaluated top-down; first match wins.',
  '# `_redirects` cannot match scheme or hostname — http:// and www. collapsing',
  '# must be configured in the Cloudflare dashboard (SSL/TLS -> Always Use',
  '# HTTPS, plus a Redirect Rule for www -> apex).',
  '',
].join('\n');

await writeFile(mergedRedirects, `${header}${[...handWritten, ...legacyPartRules].join('\n')}\n`, 'utf8');

// NOTE: dist/seo-redirects.json is deliberately NOT deleted here.
//   It is this script's own INPUT, so deleting it made the hand-off
//   non-idempotent: a second run (after a failed build, say) read nothing and
//   silently emitted a dist/_redirects 24 rules weaker than the first run's.
//   It is listed in .assetsignore, so leaving it in dist does not publish it —
//   the delete bought nothing and cost a silent regression.

console.log(`Created ${workerEntry}`);
console.log(`Created ${workerSmtp}`);
console.log(`Created ${workerRetired} (${retiredPaths.length} retired paths -> 410)`);
console.log(`Created ${assetsIgnore} (${ASSET_IGNORES.join(', ')})`);
console.log(
  `Created ${mergedRedirects} (${handWritten.length + legacyPartRules.length} rules: ` +
    `${handWritten.length} hand-written + ${legacyPartRules.length} part-page)`,
);

// A missing dist/ means astro build did not get far enough; surface it loudly
// rather than reporting a healthy merge over a stale directory.
if (!existsSync(resolve('dist/index.html'))) {
  console.warn('! dist/index.html not found — run this after a successful `astro build`.');
}

// ---------------------------------------------------------------------------
// Post-build assertions
// ---------------------------------------------------------------------------
// Two failure modes are INVISIBLE in production, so they must be impossible to
// ship. Both used to pass silently:
//
//   a. A retired (410) path still has a stored asset.
//      wrangler.toml leaves `run_worker_first` unset (= false), so Workers
//      Static Assets serves a stored asset BEFORE invoking the Worker. A
//      leftover index.html therefore answers 200 and the 410 never fires —
//      the code path that answers 410 is dead for that URL.
//      Cause in practice: Astro's own `cleanOutDir` / `cleanServerOutput`
//      deletes can fail (sandbox guard), leaving the previous build's file.
//
//   b. dist/sitemap-0.xml was not written by this build.
//      @astrojs/sitemap emits it from the `astro:build:done` hook, which runs
//      after Astro's `cleanServerOutput()` — the one call that throws when a
//      delete is refused. When the hook is skipped the file silently keeps an
//      older page set (observed 2026-10-10: sitemap three edits behind).
// ---------------------------------------------------------------------------

/**
 * Where a stored asset would live for a URL path.
 * `join` (not `resolve`) is required: a URL path starts with `/`, and
 * `resolve(DIST, '/about/')` would jump to the drive root instead of
 * `dist/about/`.
 */
function distEntryFor(urlPath) {
  return join(DIST, urlPath.replace(/^\/+/, '').replace(/\/+$/, ''));
}

function staleAssetFor(urlPath) {
  const entry = distEntryFor(urlPath);
  const candidates = [`${entry}.html`, join(entry, 'index.html'), entry];
  for (const candidate of candidates) {
    if (existsSync(candidate) && statSync(candidate).isFile()) return candidate;
  }
  return null;
}

const staleRetired = [];
for (const path of retiredPaths) {
  const asset = staleAssetFor(path);
  if (!asset) continue;
  // Best effort removal; if the delete is refused the re-check below keeps it
  // as a hard failure rather than pretending the path is clean.
  try {
    if (asset.replace(/\\/g, '/').endsWith('/index.html')) {
      rmSync(distEntryFor(path), { recursive: true, force: true });
    } else {
      rmSync(asset, { force: true });
    }
  } catch {
    /* fall through to the re-check */
  }
  const remaining = staleAssetFor(path);
  if (remaining) {
    staleRetired.push(`${path}/  (${remaining.slice(DIST.length + 1)})`);
  }
}

if (staleRetired.length) {
  failures.push(
    `${staleRetired.length} retired (410) path(s) still have a stored asset and would answer 200 ` +
      `instead of 410 (run_worker_first is false, so the asset wins):\n    ${staleRetired.join('\n    ')}\n` +
      `    Fix: delete those files (Explorer -> Shift+Delete), then re-run the build.`,
  );
}

const sitemapPath = resolve('dist/sitemap-0.xml');
const buildStartedAt = Number(process.env.BUILD_STARTED_AT_MS || 0);

// A future Astro version that writes a new server artifact to the dist root
// must not silently become a public file.
const assetIgnoreMatchers = ASSET_IGNORES.map(ignoreMatcher);
const unignoredServerOutput = readdirSync(DIST).filter((name) => {
  if (!name.endsWith('.mjs')) return false;
  const full = join(DIST, name);
  if (!statSync(full).isFile()) return false;
  return !assetIgnoreMatchers.some((matcher) => matcher.test(name));
});
if (unignoredServerOutput.length) {
  failures.push(
    `server-output file(s) at the dist root are not covered by .assetsignore, so they would be ` +
      `published as static assets:\n    ${unignoredServerOutput.join('\n    ')}\n` +
      `    Fix: add them to ASSET_IGNORES in scripts/create-worker-entry.mjs.`,
  );
}

if (!existsSync(sitemapPath)) {
  failures.push('dist/sitemap-0.xml is missing — the @astrojs/sitemap `astro:build:done` hook did not run.');
} else {
  const sitemapMtimeMs = statSync(sitemapPath).mtimeMs;
  // 1s of slack absorbs filesystem timestamp granularity; a genuinely stale
  // file is minutes behind, not milliseconds.
  if (buildStartedAt && sitemapMtimeMs + 1000 < buildStartedAt) {
    failures.push(
      `dist/sitemap-0.xml is STALE: written ${new Date(sitemapMtimeMs).toISOString()}, ` +
        `this build started ${new Date(buildStartedAt).toISOString()}. ` +
        `The sitemap therefore describes an older page set.`,
    );
  }

  const sitemapXml = await readFile(sitemapPath, 'utf8');
  const sitemapPaths = [...sitemapXml.matchAll(/<loc>([^<]+)<\/loc>/g)]
    .map((match) => new URL(match[1]).pathname);

  const retiredSet = new Set(retiredPaths.map((path) => (path.endsWith('/') ? path : `${path}/`)));
  const retiredInSitemap = sitemapPaths.filter((path) => retiredSet.has(path));
  if (retiredInSitemap.length) {
    failures.push(
      `${retiredInSitemap.length} retired (410) path(s) are listed in the sitemap — a sitemap must not ` +
        `promote URLs the site answers with 410:\n    ${retiredInSitemap.join('\n    ')}`,
    );
  }

  const missingFromDisk = sitemapPaths.filter((path) => !staleAssetFor(path));
  if (missingFromDisk.length) {
    failures.push(
      `${missingFromDisk.length} sitemap URL(s) have no built page on disk:\n    ${missingFromDisk.join('\n    ')}`,
    );
  }

  const noindexInSitemap = [];
  for (const path of sitemapPaths) {
    const file = staleAssetFor(path);
    if (!file) continue;
    const head = (await readFile(file, 'utf8')).slice(0, 4000);
    if (/<meta\s+name="robots"[^>]*noindex/i.test(head)) noindexInSitemap.push(path);
  }
  if (noindexInSitemap.length) {
    failures.push(
      `${noindexInSitemap.length} sitemap URL(s) declare robots=noindex — either drop them from the ` +
        `sitemap (src/data/sitemap-exclude.ts) or stop marking them noindex:\n    ${noindexInSitemap.join('\n    ')}`,
    );
  }

  console.log(
    `Verified ${sitemapPath} (${sitemapPaths.length} URLs` +
      `${buildStartedAt ? ', written by this build' : '; freshness not checked — BUILD_STARTED_AT_MS was not set'})`,
  );
}

if (failures.length) {
  console.error('\n' + '='.repeat(78));
  console.error(`BUILD VERIFICATION FAILED (${failures.length} problem${failures.length === 1 ? '' : 's'})`);
  console.error('='.repeat(78));
  for (const failure of failures) console.error(`\n* ${failure}`);
  console.error('\n' + '='.repeat(78));
  process.exitCode = 1;
}

